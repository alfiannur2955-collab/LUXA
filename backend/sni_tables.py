def normalize_sni_city_key(city_key: Optional[str]) -> str:
    """Resolves a city slug/name to one of the 54 canonical Tabel 8 keys (default: 'jakarta')."""
    if not city_key:
        return "jakarta"
    slug = re.sub(r"[^a-z0-9]+", "_", city_key.strip().lower()).strip("_")
    if slug in SNI_TABLE_8_SOLAR_FACTOR:
        return slug
    if slug in _CITY_ALIASES:
        return _CITY_ALIASES[slug]
    for k in SNI_TABLE_8_SOLAR_FACTOR:
        if slug in k or k in slug:
            return k
    return "jakarta"


